import { buildApp } from './app.js'

// Точка входу процесу: читає конфіг і відкриває порт. Сам застосунок збирається
// в app.ts (там же написано, чому це окремий файл).
//
// Розширення '.js' в імпорті вище — не помилка: модуль NodeNext, і шлях
// пишеться таким, яким він буде після збірки.

const app = buildApp()

// Порт поки константа: справжня конфігурація зʼявиться в Пз3 і Пз7.

const PORT = 3000

// listen повертає обіцянку, і невдалий старт приходить у catch —
// найчастіше це EADDRINUSE (порт уже зайнятий). Лог з причиною і process.exit(1)
// дають процесу зрозумілий кінець: один рядок у лозі, ненульовий код виходу.
app
  .listen({ port: PORT })
  .then((address) => app.log.info(`Сервер слухає ${address}`))
  .catch((err: unknown) => {
    app.log.error(err, 'Не вдалося підняти сервер — завершуюсь')
    process.exit(1)
  })
