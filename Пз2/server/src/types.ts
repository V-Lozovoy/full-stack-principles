// Спільні типи проєкту.
//
// Один опис — одна правда: тип відповіді описаний тут і використовується тим
// самим файлом, який цю відповідь віддає. У Пз5, коли в проєкті зʼявиться
// клієнт, він імпортуватиме типи звідси ж, а не описуватиме свої копії.

/** Відповідь GET /api/health. */
export type Health = {
  status: 'ok'
  /** Скільки секунд живе процес. */
  uptime: number
}

/**
 * Головна сутність роботи — «нотатки на мапі». Домен один для всіх: тест
 * tests/notes.test.ts перевіряє саме ці адреси і поля, тож міняти їх не можна.
 *
 * Поля, потрібні будь-якій сутності незалежно від домену:
 *   id        — щоб на неї можна було послатися адресою;
 *   createdAt — щоб список було чим сортувати;
 *   плюс якесь поле, яке має сенс міняти окремо (тут — visited, для PATCH).
 */
export type Note = {
  id: number
  title: string
  text: string | null
  lat: number
  lng: number
  tags: string[]
  visited: boolean
  /** ISO-рядок; у Пз3 стане DateTime у Prisma. */
  createdAt: string
}

/** Відповідь на список: не голий масив, а обгортка з лічильником. */
export type Page<T> = {
  items: T[]
  total: number
  page: number
  limit: number
}
