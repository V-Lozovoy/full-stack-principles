import { buildApp } from './app.js'

// Точка входу процесу: читає конфіг і відкриває порт. Сам застосунок збирається
// в app.ts (там же написано, чому це окремий файл).
//
// Розширення '.js' в імпорті вище — не помилка: модуль NodeNext, і шлях
// пишеться таким, яким він буде після збірки.

const app = buildApp()

// TODO(2) [Пз1 · Л1]: підняти сервер на порту 3000.
//   Зараз index.ts нічого не слухає, тому curl на localhost:3000 не отримує
//   навіть коду відповіді. Результат: у лозі видно адресу, а
//   curl localhost:3000/api/health відповідає (поки що 404 — маршруту ще немає,
//   це TODO(1), і навіть 404 замість мертвого з'єднання — вже прогрес).
try {
    await app.listen({ port: 3000, host: 'localhost' })
} catch (error) {
    const message = error instanceof Error ? error.message : String(error)
    app.log.error(`Server failed to start due to: ${message}`)
    process.exit(1)
}

